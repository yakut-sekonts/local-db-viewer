import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { installUpdateFixture, restoreUpdateFixture } from './update-fixture.mjs';
import { parseReleaseVersion } from '../src/release-version.ts';

const directory = await mkdtemp(join(tmpdir(), 'local-db-viewer-update-channels-'));
for (const name of ['updates', 'drivers']) await mkdir(join(directory, name));
await writeFile(join(directory, 'updates/settings.json'), JSON.stringify({ repository: 'fixture/public', automatic: false }));
await writeFile(join(directory, 'drivers/settings.json'), JSON.stringify({ automatic: false, installed: {}, selected: {} }));
const launch = () => electron.launch({ executablePath: process.env.LOCAL_DB_VIEWER_EXECUTABLE, args: process.env.LOCAL_DB_VIEWER_EXECUTABLE ? [] : [resolve('.')], env: { ...process.env, LOCAL_DB_VIEWER_DATA_DIR: directory } });
let app = await launch();
try {
  const page = await app.firstWindow();
  const current = await app.evaluate(({ app }) => app.getVersion());
  const parsed = parseReleaseVersion(current);
  if (!parsed) throw new Error('Invalid installed version');
  const stable = `${parsed.major}.${parsed.minor}.${parsed.patch + 1}`, beta = `${stable}-beta.2`;
  const fixture = { version: beta, bytes: 'x', size: 1, digest: `sha256:${createHash('sha256').update('x').digest('hex')}` };
  await installUpdateFixture(app, fixture);
  expect((await page.evaluate(() => window.studio.updates.state())).settings.channel).toBe('stable');
  expect((await page.evaluate(() => window.studio.updates.check())).phase).toBe('idle');
  await page.getByRole('button', { name: 'Обновления Local DB Viewer', exact: true }).click();
  await page.getByRole('button', { name: 'Настройки доступа к обновлениям', exact: true }).click();
  await page.getByLabel('Канал обновлений', { exact: false }).selectOption('beta');
  await page.getByRole('button', { name: 'Сохранить и проверить', exact: true }).click();
  await expect(page.getByRole('heading', { name: `Версия ${beta}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Закрыть обновления', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: beta })).toBeVisible();
  expect((await page.evaluate(() => window.studio.updates.download())).phase).toBe('ready');
  await page.getByRole('button', { name: 'Обновления Local DB Viewer', exact: true }).click();
  await page.getByRole('button', { name: 'Настройки доступа к обновлениям', exact: true }).click();
  await page.getByLabel('Канал обновлений', { exact: false }).selectOption('stable');
  await page.getByRole('button', { name: 'Сохранить и проверить', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Перезапустить и обновить', exact: true })).toHaveCount(0);
  expect(await page.evaluate(async () => { try { await window.studio.updates.install(); return false; } catch { return true; } })).toBe(true);
  await restoreUpdateFixture(app);
  await installUpdateFixture(app, { ...fixture, version: stable });
  expect((await page.evaluate(() => window.studio.updates.check())).version).toBe(stable);
  await page.getByRole('button', { name: 'Настройки доступа к обновлениям', exact: true }).click();
  await page.getByLabel('Канал обновлений', { exact: false }).selectOption('beta');
  await page.getByRole('button', { name: 'Сохранить и проверить', exact: true }).click();
  await mkdir('test-artifacts', { recursive: true });
  await page.screenshot({ path: 'test-artifacts/update-channels.png' });
  await app.close();
  app = await launch();
  const next = await app.firstWindow();
  expect((await next.evaluate(() => window.studio.updates.state())).settings.channel).toBe('beta');
  const saved = JSON.parse(await readFile(join(directory, 'updates/settings.json'), 'utf8'));
  expect(saved.channel).toBe('beta');
  await writeFile('test-artifacts/update-channels-results.json', JSON.stringify({ current, beta, stable, defaultStable: true, explicitOptIn: true, notification: true, invalidatedDownload: true, betaReceivesStable: true, retainedAfterRestart: true }, null, 2));
  console.log('Update channels verified through desktop settings, notification, download invalidation and restart.');
} finally { await app.close(); }
